const grid = document.getElementById("clubGrid");
const search = document.getElementById("clubSearch");
const count = document.getElementById("resultCount");
const empty = document.getElementById("emptyState");
const dialog = document.getElementById("storyDialog");

let activeFilter = "todos";

function renderClubs() {

  const term = search.value.trim().toLocaleLowerCase("pt-BR");

  const filtered = clubs.filter(club => {

    const matchesFilter =
      activeFilter === "todos" ||
      club.region === activeFilter ||
      (
        activeFilter === "sudeste" &&
        ["rio", "paulistas"].includes(club.region)
      );

    const searchable =
      `${club.name} ${club.state} ${club.founded} ${club.summary} ${club.facts.join(" ")}`
      .toLocaleLowerCase("pt-BR");

    return matchesFilter && searchable.includes(term);

  });

  grid.innerHTML = filtered.map(club => `

    <article
      class="club-card"
      style="--club-color:${club.color}"
      data-initial="${club.initial}"
    >

      <span class="card-region">${club.state}</span>

      <h3>${club.name}</h3>

      <span class="founded">${club.founded}</span>

      <p>${club.summary}</p>

      <a
        class="card-link"
        href="#${club.id}"
        data-story="${club.id}"
      >
        Conhecer a história <span>→</span>
      </a>

    </article>

  `).join("");

  count.textContent =
    `${filtered.length} ${filtered.length === 1 ? "história" : "histórias"}`;

  empty.hidden = filtered.length !== 0;

}

function openStory(id) {

  const club = clubs.find(item => item.id === id);

  if (!club) return;

  document.getElementById("dialogMeta").textContent =
    `${club.state} • ${club.founded}`;

  document.getElementById("dialogTitle").textContent =
    club.name;

  document.getElementById("dialogBanner").style.background =
    `linear-gradient(110deg, ${club.color} 0%, #101a28 85%)`;

  document.getElementById("dialogBody").innerHTML = `

    <h3>A trajetória</h3>

    ${club.story.map(paragraph => `<p>${paragraph}</p>`).join("")}

    <h3>Curiosidades</h3>

    <ul>
      ${club.facts.map(fact => `<li>${fact}</li>`).join("")}
    </ul>

  `;

  dialog.showModal();

}

grid.addEventListener("click", event => {

  const link = event.target.closest("[data-story]");

  if (!link) return;

  event.preventDefault();

  openStory(link.dataset.story);

});

search.addEventListener("input", renderClubs);

document.querySelectorAll(".filter-btn").forEach(button => {

  button.addEventListener("click", () => {

    document.querySelector(".filter-btn.active")
      ?.classList.remove("active");

    button.classList.add("active");

    activeFilter = button.dataset.filter;

    renderClubs();

  });

});

document.getElementById("dialogClose")
  .addEventListener("click", () => dialog.close());

dialog.addEventListener("click", event => {

  if (event.target === dialog) {
    dialog.close();
  }

});

const menuToggle = document.getElementById("menuToggle");
const mainNav = document.getElementById("mainNav");

menuToggle.addEventListener("click", () => {

  const isOpen = mainNav.classList.toggle("open");

  menuToggle.setAttribute("aria-expanded", String(isOpen));

});

mainNav.querySelectorAll("a").forEach(link => {

  link.addEventListener("click", () => {

    mainNav.classList.remove("open");

    menuToggle.setAttribute("aria-expanded", "false");

  });

});

document.getElementById("year").textContent =
  new Date().getFullYear();

renderClubs();
